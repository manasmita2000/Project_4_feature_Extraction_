"""## 16. Group importance by original feature
One-hot encoding creates many columns for features like Model, Colour, and Processor. This sums encoded importances back into their original feature groups for easier interpretation.
"""

# 1. Copy the feature importance DataFrame to work on
df_imp = importance_df.copy()

# 2. Extract the original feature name by removing the one-hot prefix (e.g., 'cat__Model_iPhone 13' -> 'Model')
# Adjust the splitting based on your preprocessor transformer names if needed
df_imp["Original_Feature"] = df_imp["Feature"].apply(
    lambda x: x.split("__")[1].split("_")[0] if "__" in x else x
)

# 3. Group by the original feature and sum their importances
grouped_importance = (
    df_imp.groupby("Original_Feature")["Importance"]
    .sum()
    .reset_index()
    .sort_values(by="Importance", ascending=False)
)

print("Importance Grouped by Original Features:")
display(grouped_importance)

